  function walkTextNodes(root, callback) {
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        if (/^(SCRIPT|STYLE|NOSCRIPT)$/.test(node.parentNode.nodeName)) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    var node;
    while ((node = walker.nextNode())) callback(node);
  }

  function setLanguage(language) {
    var chinese = language === 'zh';
    walkTextNodes(document.body, function (node) {
      if (!node._englishText) node._englishText = node.nodeValue;
      var original = node._englishText;
      var key = original.trim();
      if (!chinese || !zh[key]) {
        node.nodeValue = original;
        return;
      }
      var leading = original.match(/^\s*/)[0];
      var trailing = original.match(/\s*$/)[0];
      node.nodeValue = leading + zh[key] + trailing;
    });

    document.documentElement.lang = chinese ? 'zh-CN' : 'en';
    document.title = chinese ? 'Kimberly Maure | MLS 技术与应用专家' : 'Kimberly Maure | MLS Tech & Applications Specialist';
    var toggle = document.getElementById('language-toggle');
    if (toggle) {
      toggle.setAttribute('aria-label', chinese ? 'Switch language to English' : '切换为中文');
      toggle.setAttribute('aria-pressed', chinese ? 'true' : 'false');
    }
    var portrait = document.querySelector('.splash-photo img');
    if (portrait) portrait.alt = chinese ? 'Kimberly Maure 肖像' : 'Portrait of Kimberly Maure';
    try { localStorage.setItem('portfolio-language', language); } catch (error) {}
  }

  document.addEventListener('DOMContentLoaded', function () {
    var current = 'en';
    try { current = localStorage.getItem('portfolio-language') === 'zh' ? 'zh' : 'en'; } catch (error) {}
    setLanguage(current);
    var toggle = document.getElementById('language-toggle');
    if (toggle) {
      toggle.addEventListener('click', function () {
        current = document.documentElement.lang === 'zh-CN' ? 'en' : 'zh';
        setLanguage(current);
      });
    }
  });
